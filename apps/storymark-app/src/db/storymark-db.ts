import Dexie from "dexie";
import type { Table } from "dexie";
import type {
  BookEvent,
  BookSummary,
  EntitySummary,
  MemorySnapshot,
  Relationship,
  Section,
  SectionSummary,
  StoryGuideEntity,
} from "@storymark/shared-types";

/** A book's section manifest, cached for offline reading. `cachedAt` (epoch ms)
 * drives a short TTL: a fresh row is served directly, a stale one is refreshed
 * online but still rendered offline — so server-side title changes (e.g. a
 * section-title backfill) surface without the reader having to clear storage.
 * `version` gates it like the section rows: a reprocess can change the section
 * *count*, and a TTL-only manifest would keep serving the old TOC (indefinitely
 * offline) while the version-gated section caches had already moved on.
 * `imagesWarmedForVersion` records that the book's inline images have been pushed
 * into the service worker's `book-images` cache for that version, so re-opening a
 * cached book skips the per-section HTML parse + per-image fetch entirely. */
export interface CachedManifest {
  readonly bookId: string;
  readonly sections: readonly SectionSummary[];
  readonly cachedAt: number;
  readonly version?: BookVersion;
  readonly imagesWarmedForVersion?: BookVersion;
}

/** Full section content, cached and keyed by [bookId+sectionIndex]. Tagged with the
 * book's extraction `version` (like the memory surfaces below) so a reprocess — which
 * rewrites section HTML, paragraph offsets, or the visible-entities array — invalidates
 * the row instead of leaving stale content in IndexedDB forever. Absent on rows cached
 * before versioning, which are therefore never treated as current. */
export interface CachedSection extends Section {
  readonly bookId: string;
  readonly version?: BookVersion;
}

/** A memory snapshot cached for the section-entry recap, keyed by
 * [bookId+enteringSection] — the section whose entry the snapshot recaps (its
 * boundary is the *previous* section). Lets the recap render offline. */
export interface CachedMemory {
  readonly bookId: string;
  readonly enteringSection: number;
  readonly snapshot: MemorySnapshot;
  readonly version?: BookVersion;
}

/** The book's extraction version — its `updatedAt`, bumped whenever a processing job
 * rewrites derived data. Stored on each cached memory surface so a reprocess
 * invalidates it (the row is refetched rather than reused). Absent on rows cached
 * before versioning, which are therefore never treated as current. */
export type BookVersion = string;

/** The events visible at a reading position, cached for the timeline tab and keyed
 * by [bookId+upToSection]. `upToLocation` records the in-section position the row was
 * built at: the backend filters events to `(upToSection, upToLocation)`, so the
 * read-through cache serves a row only at or behind that boundary, never ahead of it
 * (which would leak later-in-section events). `cachedAt` (epoch ms) drives a short
 * TTL: a fresh exact-boundary row is served directly, an older one is refreshed online
 * but still rendered offline as a safe subset. */
export interface CachedTimeline {
  readonly bookId: string;
  readonly upToSection: number;
  readonly upToLocation: number;
  readonly events: readonly BookEvent[];
  readonly cachedAt: number;
  readonly version?: BookVersion;
}

/** The relationships visible at a reading position, cached for the graph tab and
 * keyed by [bookId+upToSection]. `upToLocation` and the TTL behave exactly like
 * {@link CachedTimeline}: the row is gated to the reader's boundary so a relationship
 * first seen later in the section is never served ahead of it. */
export interface CachedGraph {
  readonly bookId: string;
  readonly upToSection: number;
  readonly upToLocation: number;
  readonly relationships: readonly Relationship[];
  readonly cachedAt: number;
  readonly version?: BookVersion;
}

/** The Story Guide entities visible at a reading position, cached and keyed by
 * [bookId+upToSection] with the same boundary gating and TTL as {@link CachedTimeline}.
 * The entity list supplies the Story Guide, the timeline's involved-name lookups, and
 * the graph's nodes, so caching it is what lets all three render offline. */
export interface CachedEntities {
  readonly bookId: string;
  readonly upToSection: number;
  readonly upToLocation: number;
  readonly entities: readonly StoryGuideEntity[];
  readonly cachedAt: number;
  readonly version?: BookVersion;
}

/** A spoiler-safe entity summary cached for the entity popup, keyed by
 * [bookId+entityId+upToSection]. The summary is generated by the server gated to a
 * reading position, so `upToLocation` records the boundary it was built at: the
 * read-through cache serves a row only at or behind the reader (never ahead — that
 * would leak later-in-section content), exactly like {@link CachedTimeline}. Caching
 * it is what lets a tapped entity render offline instead of showing "unavailable".
 * No `cachedAt`: like a memory snapshot, the summary is stable for a given
 * (version, position), so the row never expires by TTL — `version` invalidates it
 * on a reprocess and the boundary gate handles every move of the reader. */
export interface CachedEntitySummary {
  readonly bookId: string;
  readonly entityId: string;
  readonly upToSection: number;
  readonly upToLocation: number;
  readonly summary: EntitySummary;
  readonly version?: BookVersion;
}

/** The library list, cached as a single row keyed by the literal `"all"`. The list
 * is fetched network-first (books-api) and this row is the offline fallback. It is
 * deliberately the *only* offline copy: a service-worker cache for `/api/books` would
 * be keyed by URL alone and so serve one account's library to another on a shared
 * device (ADR-0023) — this row lives in the per-user partition instead. `cachedAt`
 * (epoch ms) is informational. */
export interface CachedLibrary {
  readonly id: "all";
  readonly books: readonly BookSummary[];
  readonly cachedAt: number;
}

/** Reader typography/theme settings. One row per cache partition (i.e. per
 * account, ADR-0023), keyed by the literal `"global"` within it. */
export interface StoredReaderSettings {
  readonly id: "global";
  readonly fontFamily: ReaderFontFamily;
  readonly fontSizePx: number;
  readonly lineHeight: number;
  readonly paragraphSpacingEm: number;
  readonly contentWidthPx: number;
  readonly pageMarginPx: number;
  readonly theme: ReaderTheme;
  readonly entityHighlight: EntityHighlightMode;
  readonly recapCardOnSectionEntry: boolean;
  readonly fullscreen: boolean;
}

export type ReaderFontFamily = "serif" | "sans" | "mono" | "dyslexic" | "lexend";
export type ReaderTheme = "light" | "sepia" | "dark";
export type EntityHighlightMode = "off" | "default" | "subtle";

/** The local copy of a bookmark plus its sync state. `synced=false` means there
 * is a pending operation: a create (`deleted=false`) to POST, or a tombstone
 * (`deleted=true`) to DELETE on the server, flushed on reconnect. */
export interface StoredBookmark {
  readonly id: string;
  readonly bookId: string;
  readonly sectionIndex: number;
  readonly paragraphIndex: number;
  readonly locationStart: number;
  readonly label: string | null;
  readonly createdAt: string;
  readonly synced: boolean;
  readonly deleted: boolean;
}

/** The local mirror of a book's reading position (one row per book). Doubles as
 * the offline-resume cache and the sync queue: `synced=false` means the position
 * has not yet been accepted by the backend and is flushed on reconnect. */
export interface StoredProgress {
  readonly bookId: string;
  readonly sectionIndex: number;
  readonly paragraphIndex: number;
  /** Exact paginated column within the section on this device/layout. This is
   * local-only: server sync remains paragraph/location based because page numbers
   * are not portable across devices, viewport sizes, or reader settings. */
  readonly pageIndex?: number;
  readonly locationStart: number;
  readonly locationEnd: number;
  readonly clientTimestamp: string;
  readonly synced: boolean;
}

/** When a book was last opened (one row per book), in ISO 8601. Drives the
 * "Previously…" recap on reopen after a long gap. */
export interface StoredBookOpen {
  readonly bookId: string;
  readonly lastOpenedAt: string;
}

/** Where the session ended (one row, keyed by the literal `"current"`): a book id
 * when the reader was the last screen, null when it was anything else — library,
 * upload, admin. Drives the cold-load redirect, which must distinguish "closed the
 * app mid-book" (resume the book) from "closed it on the library" (stay there) —
 * `bookOpens` can't tell those apart, it only records that a book was opened. */
export interface StoredLastLocation {
  readonly id: "current";
  readonly bookId: string | null;
}

/** The last-active Memory panel tab for a book (one row per book), so reopening
 * the panel lands on the tab the reader left it on. `lastTab` is stored loosely as
 * a string and validated against the known tabs on read (the tab set can change
 * between releases). */
export interface StoredPanelState {
  readonly bookId: string;
  readonly lastTab: string;
}

// The `as Dexie & { … }` pattern types the tables without subclassing Dexie,
// which would force definite-assignment (`!`) fields the no-non-null-assertion
// rule forbids. The schema string below is the source of truth for indexes.
type StorymarkDb = Dexie & {
  library: Table<CachedLibrary, string>;
  manifests: Table<CachedManifest, string>;
  sections: Table<CachedSection, [string, number]>;
  readerSettings: Table<StoredReaderSettings, string>;
  progress: Table<StoredProgress, string>;
  bookmarks: Table<StoredBookmark, string>;
  memorySnapshots: Table<CachedMemory, [string, number]>;
  bookOpens: Table<StoredBookOpen, string>;
  timelines: Table<CachedTimeline, [string, number]>;
  graphs: Table<CachedGraph, [string, number]>;
  entities: Table<CachedEntities, [string, number]>;
  entitySummaries: Table<CachedEntitySummary, [string, string, number]>;
  panelState: Table<StoredPanelState, string>;
  lastLocation: Table<StoredLastLocation, string>;
};

function createDb(name: string): StorymarkDb {
  const instance = new Dexie(name) as StorymarkDb;

  // The schema string is the source of truth for indexes. `synced`/`deleted` flags
  // are not indexed — booleans aren't valid IndexedDB key types, and with a handful
  // of books the reconnect flush filters unsynced rows in memory.
  instance.version(1).stores({
    manifests: "bookId",
    sections: "[bookId+sectionIndex]",
    readerSettings: "id",
    progress: "bookId",
    bookmarks: "id, bookId",
    memorySnapshots: "[bookId+enteringSection]",
    bookOpens: "bookId",
    timelines: "[bookId+upToSection]",
    graphs: "[bookId+upToSection]",
    entities: "[bookId+upToSection]",
    panelState: "bookId",
  });

  // v2 adds the library list cache. Dexie carries the v1 stores forward, so only the
  // new store is declared here. The single row is keyed by the literal "all".
  instance.version(2).stores({
    library: "id",
  });

  // v3 adds `upToLocation` to the timeline/graph/entity rows so the read-through cache
  // can gate them by the reader's in-section position (see CachedTimeline). The key
  // (still [bookId+upToSection]) is unchanged, so no schema delta — but legacy rows
  // lack the new field, which would defeat the boundary check, so they are cleared and
  // refetched on next open.
  instance.version(3).upgrade(async (tx) => {
    await Promise.all([
      tx.table("timelines").clear(),
      tx.table("graphs").clear(),
      tx.table("entities").clear(),
    ]);
  });

  // v4 adds the per-entity summary cache (keyed [bookId+entityId+upToSection]) so a
  // tapped entity renders offline instead of "unavailable". A new store starts empty,
  // so there is no upgrade body. Dexie carries the prior stores forward.
  instance.version(4).stores({
    entitySummaries: "[bookId+entityId+upToSection]",
  });

  // v5 adds the last-location row (see StoredLastLocation). Existing installs are
  // seeded from their most recent bookOpens row: the pre-v5 redirect resumed the
  // last-opened book unconditionally, and seeding keeps that first post-upgrade
  // reopen behaving as before instead of dumping every reader on the library once.
  instance
    .version(5)
    .stores({ lastLocation: "id" })
    .upgrade(async (tx) => {
      const opens = await tx.table<StoredBookOpen, string>("bookOpens").toArray();
      if (opens.length === 0) {
        return;
      }
      const latest = opens.reduce((a, b) => (b.lastOpenedAt > a.lastOpenedAt ? b : a));
      await tx
        .table<StoredLastLocation, string>("lastLocation")
        .put({ id: "current", bookId: latest.bookId });
    });

  // A release that adds a db.version() above upgrades the on-device database on
  // first open, and IndexedDB runs that upgrade only once every *other* connection
  // to it has closed. If a second tab — or the still-resident installed PWA — holds
  // the previous version open, the upgrade blocks indefinitely and every query
  // against `db` hangs with no error (a silent "stuck on first load" after a release
  // that adds a store). Closing on `versionchange` yields to the newer instance
  // instead of deadlocking against it.
  instance.on("versionchange", () => {
    instance.close();
  });

  return instance;
}

const LAST_USER_STORAGE_KEY = "storymark.lastUserId";

// The cache is one IndexedDB database per account (ADR-0023): the database name
// carries the partition, so keys, indexes, and every call site stay unchanged, and
// nothing cached for one account — private book content included — is reachable
// from another's partition. The last-known user picks the partition before the
// session can be probed (offline cold start), and keeps serving it when a cookie
// expires offline; only an actual sign-in moves it.
function partitionName(userId: string | null): string {
  return userId === null ? "storymark.u.none" : `storymark.u.${userId}`;
}

let currentUserId: string | null = localStorage.getItem(LAST_USER_STORAGE_KEY);
let current = createDb(partitionName(currentUserId));

// A swappable handle rather than a per-call-site lookup: a dozen modules read
// `db.<table>` at call time, and this keeps the partition switch in one place
// instead of threading a user id through every cache access. Methods are bound
// so `db.close()`-style calls keep their receiver.
export const db = new Proxy({} as StorymarkDb, {
  get(_target, property): unknown {
    const value: unknown = Reflect.get(current, property);
    return typeof value === "function" ? value.bind(current) : value;
  },
}) as StorymarkDb;

/** Points the cache at the given account's partition and persists it as the
 * device's last-known user. Returns true when this moved away from a
 * *different* signed-in account — module-level state (library list, reader
 * settings, sync registrations) still holds the previous partition's data in
 * memory, so the caller must restart the app shell with a full navigation. */
export function switchCachePartition(userId: string): boolean {
  // Persisted even when the partition doesn't move: a logout removed the
  // stored pointer (forgetLastUser) while this handle kept serving the same
  // account, and a re-login must restore it for the next cold start.
  localStorage.setItem(LAST_USER_STORAGE_KEY, userId);
  if (userId === currentUserId) {
    return false;
  }
  const previous = currentUserId;
  currentUserId = userId;
  current.close();
  current = createDb(partitionName(userId));
  return previous !== null;
}

/** Forgets the device's last-known user so the next cold start opens the empty
 * anonymous partition instead of the signed-out account's — an offline cold
 * start must not hand that account's library to whoever holds the device. The
 * partition data itself is kept (cached books stay warm for a re-login), as is
 * the in-memory handle: it still backs the current tab, and the next sign-in
 * either re-persists it (same account) or swaps it (different account). */
export function forgetLastUser(): void {
  localStorage.removeItem(LAST_USER_STORAGE_KEY);
}

/** Whether the device remembers a signed-in account — i.e. whether an
 * unreachable session probe has a cached partition to fall back on. False on a
 * fresh device and after an explicit sign-out ({@link forgetLastUser}). */
export function hasLastKnownUser(): boolean {
  return localStorage.getItem(LAST_USER_STORAGE_KEY) !== null;
}

/** The account the server's AddUsers migration seeds; the client needs it offline
 * (this migration runs before any session probe), so the id is duplicated here by
 * necessity — it must match the migration's value. */
const SEED_USER_ID = "00000000-0000-0000-0000-000000000001";

/** One-time move of the pre-multi-user cache (the unpartitioned `storymark`
 * database) into the seeded initial account's partition — all pre-auth local
 * state belonged to that account, mirroring the server-side adoptions in the
 * AddUsers/AddUserScopeToReaderState migrations. Copying rather than clearing
 * preserves offline books and any unsynced progress/bookmark queue across the
 * upgrade. A no-op once the legacy database is gone. */
export async function migrateLegacyCache(): Promise<void> {
  if (!(await Dexie.exists("storymark"))) {
    return;
  }

  // No version spec: Dexie opens the legacy database in dynamic mode, with
  // whatever schema it last had.
  const legacy = new Dexie("storymark");
  await legacy.open();
  const target = createDb(partitionName(SEED_USER_ID));
  try {
    await Promise.all(
      legacy.tables.map(async (table) => {
        const rows = await table.toArray();
        if (rows.length > 0) {
          await target.table(table.name).bulkPut(rows);
        }
      }),
    );
  } finally {
    legacy.close();
    target.close();
  }

  await Dexie.delete("storymark");

  // The migrated rows belong to the seed account, so when no user is known yet
  // (always the case on the pre-auth device's first post-upgrade launch) the
  // partition must follow them: an offline first launch would otherwise open
  // the empty anonymous partition and the migrated library — including any
  // unsynced write queue — would be unreachable until a successful sign-in.
  if (currentUserId === null) {
    switchCachePartition(SEED_USER_ID);
  }
}

// Dexie.minKey/.maxKey sort below/above every value and IndexedDB compares array
// keys element-wise (a shorter prefix sorts first), so these two-element bounds span
// the book's whole key range whatever the compound index's depth.
function deleteBookSpan<TRow, TKey extends [string, ...unknown[]]>(
  table: Table<TRow, TKey>,
  index: `[bookId+${string}]`,
  bookId: string,
): Promise<number> {
  return table.where(index).between([bookId, Dexie.minKey], [bookId, Dexie.maxKey]).delete();
}

/** Removes every locally-cached row for a book once it has been deleted on the
 * server, so nothing orphans in IndexedDB. Compound-key stores are range-deleted
 * across the book's whole key span; single-key stores delete by their key. */
export async function purgeBookData(bookId: string): Promise<void> {
  await Promise.all([
    db.manifests.delete(bookId),
    db.progress.delete(bookId),
    db.bookOpens.delete(bookId),
    db.panelState.delete(bookId),
    db.bookmarks.where("bookId").equals(bookId).delete(),
    deleteBookSpan(db.sections, "[bookId+sectionIndex]", bookId),
    deleteBookSpan(db.memorySnapshots, "[bookId+enteringSection]", bookId),
    deleteBookSpan(db.timelines, "[bookId+upToSection]", bookId),
    deleteBookSpan(db.graphs, "[bookId+upToSection]", bookId),
    deleteBookSpan(db.entities, "[bookId+upToSection]", bookId),
    deleteBookSpan(db.entitySummaries, "[bookId+entityId+upToSection]", bookId),
  ]);
}

/** Drops the cached entity-dependent surfaces for a book — the Story Guide list, the
 * timeline, the relationship graph, and section content — across their whole key span. An
 * entity merge rewrites entity identities, event involvements, and graph edges, so every
 * snapshot of these becomes stale; section rows also embed the per-section highlight entity
 * set, so a stale row would keep a folded-away entity's id (a 404 on tap). Per-entity
 * summaries are dropped for the same reason: a merge rewrites entity ids, so a cached
 * summary for a folded-away entity would 404 on tap. Clearing them forces a refetch from
 * the server (the source of truth) on the next load. Memory snapshots are untouched: a
 * merge doesn't change them. */
export async function purgeEntityDerivedCache(bookId: string): Promise<void> {
  await Promise.all([
    deleteBookSpan(db.entities, "[bookId+upToSection]", bookId),
    deleteBookSpan(db.entitySummaries, "[bookId+entityId+upToSection]", bookId),
    deleteBookSpan(db.timelines, "[bookId+upToSection]", bookId),
    deleteBookSpan(db.graphs, "[bookId+upToSection]", bookId),
    deleteBookSpan(db.sections, "[bookId+sectionIndex]", bookId),
  ]);
}

/** The book the previous session ended on, or null when it ended outside the
 * reader (or nothing is recorded yet). Drives the cold-load redirect: only a
 * session closed mid-book resumes that book. */
export async function getLastLocationBookId(): Promise<string | null> {
  const row = await db.lastLocation.get("current");
  return row?.bookId ?? null;
}

/** Records where the user is right now — the open book's id in the reader, null on
 * any other screen — so a cold start can land where the session ended. */
export async function setLastLocation(bookId: string | null): Promise<void> {
  await db.lastLocation.put({ id: "current", bookId });
}

/** True if any locally-queued reading-position or bookmark write hasn't reached the
 * server yet. {@link clearCachedData} drops the sync queue, so the caller flushes and
 * re-checks this first to avoid discarding unsynced changes. */
export async function hasUnsyncedChanges(): Promise<boolean> {
  const [progress, bookmarks] = await Promise.all([
    db.progress.filter((row) => !row.synced).count(),
    db.bookmarks.filter((row) => !row.synced).count(),
  ]);
  return progress > 0 || bookmarks > 0;
}

/** Clears every locally-cached and sync-queue table, keeping only the reader's
 * settings. Everything cleared re-hydrates from the server (the source of truth) on
 * next load, so flush pending writes and confirm none remain (via
 * {@link hasUnsyncedChanges}) before calling this. */
export async function clearCachedData(): Promise<void> {
  await Promise.all(
    db.tables.filter((table) => table.name !== "readerSettings").map((table) => table.clear()),
  );
}
